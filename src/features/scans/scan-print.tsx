import { SEVERITIES } from '@/components/ui/severity';
import { gradeOf, scoreOf } from '@/lib/grade';
import type { ApiFinding } from '@/lib/api/schemas';
import { formatTimestamp } from '@/lib/format';
import { diffFindings } from '@/lib/scan-diff';
import { neutralFix } from './fix-snippets';
import { CATEGORY_LABEL, groupFindings } from './scan-detail';

type PrintScan = {
  target: string;
  scannerVersion: string;
  finishedAt: string;
  summary: Parameters<typeof scoreOf>[0];
  findings: ApiFinding[];
};

/**
 * The PDF layout. It is hidden on screen and shown only when printing ("Save as PDF"), written in
 * plain light colours because the app itself is dark-only and printing a dark page wastes ink.
 * Everything is expanded: a printed page cannot be clicked open.
 */
export function ScanPrint({
  scan,
  previous,
}: {
  scan: PrintScan;
  previous?: { finishedAt: string; findings: ApiFinding[] };
}) {
  const score = scoreOf(scan.summary);
  const grade = gradeOf(score);
  const diff = previous ? diffFindings(previous.findings, scan.findings) : null;
  const priorities = [...scan.findings]
    .filter((f) => f.severity !== 'INFO')
    .sort((a, b) => SEVERITIES.indexOf(a.severity) - SEVERITIES.indexOf(b.severity))
    .slice(0, 3);

  return (
    <article className="hidden bg-white text-[11pt] leading-snug text-black print:block">
      <header className="border-b-2 border-black pb-3">
        <p className="text-[9pt] uppercase tracking-widest text-gray-600">
          Security assessment report
        </p>
        <h1 className="mt-1 break-all text-[20pt] font-semibold">{scan.target}</h1>
        <p className="mt-1 text-[9pt] text-gray-600">
          Scanned {formatTimestamp(scan.finishedAt)} UTC · sentinel-scanner v{scan.scannerVersion}
        </p>
      </header>

      <section className="mt-5 flex items-center gap-6 break-inside-avoid">
        <div className="flex h-20 w-20 items-center justify-center border-4 border-black text-[36pt] font-bold">
          {grade}
        </div>
        <div>
          <p className="text-[16pt] font-semibold">{score}/100</p>
          <p className="text-gray-700">
            {scan.findings.length === 0
              ? 'No findings.'
              : SEVERITIES.filter((s) => (scan.summary[s] ?? 0) > 0)
                  .map((s) => `${scan.summary[s]} ${s.toLowerCase()}`)
                  .join(' · ')}
          </p>
          {diff && (
            <p className="text-gray-700">
              Since the previous scan: {diff.fixed.length} fixed, {diff.added.length} new,{' '}
              {diff.unchanged} unchanged.
            </p>
          )}
        </div>
      </section>

      {priorities.length > 0 && (
        <section className="mt-5 break-inside-avoid">
          <h2 className="text-[13pt] font-semibold">Fix first</h2>
          <ol className="mt-1 list-decimal pl-5">
            {priorities.map((f) => (
              <li key={f.id}>
                <strong>[{f.severity}]</strong> {f.title}
              </li>
            ))}
          </ol>
        </section>
      )}

      {groupFindings(scan.findings).map(({ category, findings }) => (
        <section key={category} className="mt-6">
          <h2 className="border-b border-gray-400 pb-1 text-[13pt] font-semibold">
            {CATEGORY_LABEL[category]}
          </h2>
          {findings.map((f) => (
            <div key={f.id} className="mt-3 break-inside-avoid">
              <p className="font-semibold">
                <span className="mr-2 border border-black px-1 text-[9pt] uppercase">
                  {f.severity}
                </span>
                {f.title}
              </p>
              <p className="text-[9pt] text-gray-600">{f.checkId}</p>
              <p className="mt-1 whitespace-pre-wrap break-words">{f.description}</p>
              <p className="mt-1">
                <strong>Fix:</strong> <span className="whitespace-pre-wrap">{f.remediation}</span>
              </p>
              {neutralFix(f.checkId) && (
                <p className="mt-1 font-mono text-[9pt]">{neutralFix(f.checkId)}</p>
              )}
              {f.references.length > 0 && (
                <p className="mt-1 break-all text-[9pt] text-gray-600">
                  {f.references.join('  ·  ')}
                </p>
              )}
            </div>
          ))}
        </section>
      ))}

      <footer className="mt-8 border-t border-gray-400 pt-2 text-[8pt] text-gray-600">
        Generated by Sentinel. Passive, read-only checks (GET/HEAD requests, no attack payloads),
        run against a target the operator owns or is authorised to test. This is an automated
        assessment, not a penetration test; categories without findings were clean or not part of
        the scan.
      </footer>
    </article>
  );
}
